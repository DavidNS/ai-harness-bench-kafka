package org.apache.kafka.clients.consumer.internals.events;

import org.apache.kafka.common.utils.LogContext;

import java.util.concurrent.BlockingQueue;
import java.util.concurrent.atomic.AtomicReference;

/**
 * An {@link EventProcessor} that is created and executes in the application thread for the purpose of processing
 * {@link BackgroundEvent background events} generated by the {@link org.apache.kafka.clients.consumer.internals.ConsumerNetworkThread network thread}.
 * Those events are generally of two types:
 *
 * <ul>
 *     <li>Errors that occur in the network thread that need to be propagated to the application thread</li>
 * </ul>
 */
public class BackgroundEventProcessor extends EventProcessor<BackgroundEvent> {

    public BackgroundEventProcessor(final LogContext logContext,
                                    final BlockingQueue<BackgroundEvent> backgroundEventQueue) {
        super(logContext, backgroundEventQueue);
    }

    /**
     * Process the events—if any—that were produced by the network thread. In this case, errors resulting from
     * processing the events are rethrown on the calling (application) thread. All the available events are processed
     * before the first error is rethrown; any further errors are added to it as suppressed exceptions.
     */
    @Override
    public void process() {
        AtomicReference<RuntimeException> firstError = new AtomicReference<>();

        process((event, error) -> {
            if (!firstError.compareAndSet(null, error))
                firstError.get().addSuppressed(error);
        });

        RuntimeException error = firstError.get();

        if (error != null)
            throw error;
    }

    @Override
    public void process(final BackgroundEvent event) {
        if (event.type() == BackgroundEvent.Type.ERROR)
            process((ErrorBackgroundEvent) event);
        else
            throw new IllegalArgumentException("Background event type " + event.type() + " was not expected");
    }

    @Override
    protected Class<BackgroundEvent> getEventClass() {
        return BackgroundEvent.class;
    }

    private void process(final ErrorBackgroundEvent event) {
        throw event.error();
    }
}
